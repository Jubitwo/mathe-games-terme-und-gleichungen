PX = 100          # Pixelgröße in Font-Einheiten
ASC = 7 * PX
UPM = 1000
ADV = 6 * PX


def glyph_for(rows):
    pen = TTGlyphPen(None)
    for r, row in enumerate(rows):
        for c, ch in enumerate(row):
            if ch != '#':
                continue
            x0, y1 = c * PX, ASC - r * PX
            x1, y0 = x0 + PX, y1 - PX
            pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
    return pen.glyph()


def main():
    names = ['.notdef', 'space']
    glyphs = {'.notdef': TTGlyphPen(None).glyph(), 'space': TTGlyphPen(None).glyph()}
    cmap = {32: 'space', 160: 'space'}
    metrics = {'.notdef': (ADV, 0), 'space': (ADV, 0)}
    for i, (ch, rows) in enumerate(G.items()):
        n = 'g%03d' % i
        names.append(n)
        glyphs[n] = glyph_for(rows)
        metrics[n] = (ADV, 0)
        cmap[ord(ch)] = n
        low = ch.lower()
        if low != ch and len(low) == 1:
            cmap[ord(low)] = n
    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=800, descent=-200)
    fb.setupNameTable({'familyName': 'ArenaPixel', 'styleName': 'Regular'})
    fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, usWinAscent=800, usWinDescent=200)
    fb.setupPost()
    out = os.path.join(os.path.dirname(__file__), '..', 'assets', 'fonts', 'ArenaPixel.ttf')
    fb.save(out)
    print('gespeichert:', os.path.abspath(out))


if __name__ == '__main__':
    main()
